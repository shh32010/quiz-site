Fabric 根据交易过程中不同环节的功能，在逻辑上将节点角色解耦为 Endorser 和 Committer，让不同类型节点关注处理不同类型的工作负载。典型交易处理过程为：客户端从 CA 获取身份证书并加入应用通道；构造交易提案（Proposal）提交给 Endorser 背书；收集到足够（由背书策略决定）的背书支持后构造合法交易请求，发给 Orderer 排序；Orderer 将排序后的交易打包成区块，分发给 Committer 落盘。

各组件功能如下：

- 客户端（App）：使用 SDK 与 Fabric 网络交互，负责获取证书、构造并提交交易提案、收集背书、提交交易，并可通过事件机制监听网络消息，以确认交易是否被成功接收；
- Endorser 节点：完成对交易提案的背书（目前主要是签名）。收到提案后先做合法性和 ACL 权限检查，通过则模拟运行交易，对交易引起的状态变化以读写集形式（读状态的键和版本、写状态的键值）进行背书并返回结果；
- Committer 节点：维护区块链和账本结构（状态数据库、历史数据库、索引数据库等），定期从 Orderer 获取排序后的批量交易区块，落盘前做最终检查（交易消息结构、签名完整性、是否重复、读写集版本是否匹配等），通过后执行合法交易、写入账本并构造新区块；
