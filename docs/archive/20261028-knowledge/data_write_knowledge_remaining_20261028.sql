无线局域网采用的标准：IEEE 802.11、IEEE 802.11b。

IEEE 802.11 标准由 IEEE 802 于 1997 年公布，是组建无线局域网的最初标准，主要用于解决办公室局域网、校园网中用户和用户终端的无线接入业务，仅限于数据存取，速率最高能达 2Mbit/s。该标准中定义了两类设备：无线站（通常由一台计算机加上一块无线网卡构成）和无线访问节点（Wireless Network Access Point），即无线 AP。

1999 年 9 月，IEEE 802 提出了 IEEE 802.11b 标准，是对 IEEE 802.11 标准的补充，主要是增加了 5.5Mbit/s 和 11Mbit/s 两个通信速率。

2. 无线局域网的组网设备：无线网卡、无线 AP。

无线网卡有 3 种类型：PCMCIA 无线网卡（笔记本电脑专用）、PCI 无线网卡（台式计算机专用）、USB 无线网卡（笔记本电脑和台式计算机都可以使用）。

PCMCIA 无线网卡专用于笔记本电脑，与有线网卡的区别在于用无线发送、接收电路代替了 RJ-45 接口，比有线网卡多了天线部分。PCI 无线网卡主要用于台式计算机组建无线局域网，这种网卡在 PCMCIA 无线网卡的基础上添加了一块 PCI 转接卡，使用时先将 PCI 转接卡插到计算机主板插槽内，然后再将无线网卡插到 PCI 转接卡中。USB 无线网卡是通过 USB 接口和计算机相连的无线收发设备，既可用于笔记本电脑，也可用于台式计算机，是当前比较流行的无线网卡类型。

无线 AP 就相当于有线网络中的 Hub，将多个无线终端汇接在一起，实现互连。其结构为一块无线网卡加一个或多个 RJ-45 接口：无线网卡用来接收和发送无线数据，RJ-45 接口用来实现与有线局域网的连接。

组建无线局域网可以采用 4 种方式：网桥连接型、无线 AP 接入型、Hub 接入型、无中心接入型。
（1）网桥连接型：选用具有网桥功能的无线 AP，将两个有线局域网通过无线方式连接。
（2）无线 AP 接入型：无线 AP 作为 Hub 组成星型结构的无线局域网。
（3）Hub 接入型：通过无线 AP 和有线 Hub，实现一个网络中无线部分与有线部分之间的互联。
（4）无中心接入型：类似于有线局域网中的对等网，这种无线网络不能与其他网络连接。

