结构图的基本术语：
深度：模块结构的层次数（控制的层数）。
宽度：同一层模块的最大模块数。
扇出：一个模块直接调用的其他模块数目。
扇入：调用一个给定模块的模块数目（被调用的次数）。

好的软件结构应该是顶层扇出比较多，中层扇出较少，底层扇入多。

