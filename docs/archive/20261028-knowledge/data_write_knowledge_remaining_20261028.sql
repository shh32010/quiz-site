基本思想：将软件设计成由相对独立且具有单一功能的模块组成的结构，分为概要设计和详细设计两个阶段。概要设计阶段的描述工具是结构图（SC）。

概要设计也称结构设计或总体设计，主要任务是把系统的功能需求分配给软件结构，形成软件的模块结构图。

结构图是软件结构概要设计阶段的工具，反映系统的功能实现以及模块与模块之间的联系与通信，即反映系统的总体结构。

