## Use Case 与活动者

Use Case 指系统的外部事物（活动者）与系统的交互，表达系统的功能，即系统所提供的服务。Use Case 是关于系统的一组动作的说明，这些动作对一个或多个活动者给出所需要的结果。Use Case 用于为待开发的系统建立功能需求模型；Use Case 图是 Use Case 模型的图形表示，能准确表达活动者与系统的交互情况和系统提供的服务，是后续系统分析与设计工作的依据，也是系统测试的依据。

活动者（Actor）是用户作用于系统的一个角色，用来建立系统的外部用户模型，是对系统边界之外的对象的描述。活动者与系统的交互包括信息交换（数据信息和控制信息）和与系统的协同。活动者包括人活动者和外部系统活动者；活动者不一定是人，也可以是与本系统相互作用、交换信息的外部系统。一个活动者可以运行多个 Use Case，一个 Use Case 也可以由多个活动者运行。活动者之间可以有泛化联系，即一个活动者可以继承更一般的活动者的特性。

确定活动者首先应明确系统的范围，凡与系统进行信息交换（包括数据信息和控制信息交换）的外部事物，如人员、设备、外部系统，都可以确认为活动者。

## 业务 Use Case 与系统 Use Case

业务 Use Case 指系统提供的业务功能与活动者（用户）的交互，表现问题领域中各实体之间的联系和业务往来活动，用于建立问题领域的业务 Use Case 模型。系统 Use Case 指活动者与系统的交互，表现系统的功能需求和动态行为，用于建立系统的 Use Case 模型。每一个业务 Use Case 都要由一组系统 Use Case 支持。在系统开发的开端阶段应把注意力集中在业务 Use Case 上，在精化阶段和构建阶段再考虑系统 Use Case。

## Use Case 图的层次

按抽象层次，Use Case 图可划分为系统层（最高层）、子系统层和对象类层（最低层）。系统层 Use Case 图描述系统提供的全部服务；子系统层 Use Case 图描述子系统提供的服务，其外部交互者可以是其他子系统或高一层的活动者；对象类层的 Use Case 图描述对象类提供的功能片或操作。开发过程中 Use Case 图可以自顶向下不断精化，抽象出不同层次的 Use Case 图。

