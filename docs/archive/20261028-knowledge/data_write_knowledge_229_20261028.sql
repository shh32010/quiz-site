## 区块链简介

区块链是一个分布式账本，一种通过去中心化、去信任的方式集体维护可靠数据库的技术方案，其本身是一系列使用密码学产生的、互相关联的数据块。

## 从数据的角度来看

区块链是一种几乎不可能被更改的分布式数据库。“分布式”不仅体现为数据的分布式存储，也体现为数据的分布式记录（即由系统参与者共同维护）。

## 从技术的角度来看

区块链并不是一种单一的技术，而是多种技术整合的结果。这些技术以新的结构组合在一起，形成了一种新的数据记录、存储和表达的方式。

## 关键点

去中心化、去信任、集体维护、可靠数据库、时间戳、非对称加密。

按照国际标准化组织的定义，区块链是“采用密码学手段保障的、只可追加的、通过块链式结构组织的分布式账本结构”。

区块链技术指使用点对点传输、共识机制、加密算法等技术，保证分布式数据库中写入链的数据的一致性，达到去中心化和不可篡改的目的；它是各种技术的结合，建立了一种全新的技术架构。

简单理解，就是把数据库比作一个账本，一次记账就是一次数据库的读写；产生数据时，在一段时间内谁最先拿到记账权，就由这个人来记账，然后把账本信息发给系统中的其他所有人，所有人达成共识时本次记账有效，账本上的数据此后谁也无权修改。

区块链实质上是一个不断增长的分布式结算数据库，能够解决信任危机。信任建立在区块链上，不由单个组织掌控，其公信力被多方交叉验证与监督。与其他费时又费钱的中心化工具相比，区块链能对已经设定并上链的交易进行实时自动撮合、强制执行，而且成本很低。

## 开放、共识

任何人都可以参与区块链网络，每一台设备都能作为一个节点，每个节点都允许获得一份完整的数据库拷贝。节点间基于一套共识机制，通过竞争计算共同维护整个区块链；任一节点失效，其余节点仍能正常工作。

## 去中心、去信任

区块链由众多节点共同组成一个端到端的网络，不存在中心化的设备和管理机构。节点之间的数据交换通过数字签名技术进行验证，无需互相信任，只要按照系统既定的规则进行，节点之间不能也无法欺骗其他节点。

## 交易透明、双方匿名

区块链的运行规则是公开透明的，所有数据信息也是公开的，因此每笔交易都对所有节点可见。由于节点之间是去信任的，节点之间无需公开身份，每个参与的节点都是匿名的。

## 不可篡改、可追溯

单个甚至多个节点对数据库的修改无法影响其他节点的数据库，除非能控制整个网络中超过 51% 的节点同时修改，而这几乎不可能发生。区块链中的每笔交易都通过密码学方法与相邻两个区块串联，因此可以追溯到任何一笔交易的前世今生。

