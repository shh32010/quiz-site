虚拟化（Virtualization）是一种资源管理技术，将计算机的各种实体资源（如服务器、网络、内存及存储等）予以抽象、转换后呈现出来，打破实体结构间不可切割的障碍，使用户能以比原本更好的方式应用这些资源。这些资源的虚拟部分不受现有资源的架设方式、地域或物理配置的限制。一般所指的虚拟化资源包括计算能力和数据存储。从技术上讲，虚拟化是在软件中仿真计算机硬件；从表现形式上看，虚拟化分为两种应用模式：一台强服务器虚拟为多台小服务器，或多台服务器虚拟为一台强服务器。虚拟化的本质是将原来运行在真实环境上的计算系统或组件运行在虚拟出来的环境中，其主要目的是简化 IT 基础设施，简化对资源以及对资源管理的访问。

按应用领域划分，虚拟化技术包括服务器虚拟化、存储虚拟化、应用虚拟化、平台虚拟化和桌面虚拟化；按实现方式，服务器虚拟化分为原生虚拟化和寄宿虚拟化。虚拟化解除了应用与操作系统和硬件的耦合关系，为应用程序屏蔽了底层可能与其他应用产生的冲突。

