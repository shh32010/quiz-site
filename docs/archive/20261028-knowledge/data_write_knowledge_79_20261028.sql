update t_knowledge_point set title = $kp$存储结构、栈与队列、树与图结构要点$kp$, content = $kp$一、存储结构
顺序存储：元素存储在连续的空间中。若元素大小为 1B，则从内存 0# 地址开始，元素的下标就是地址码；若元素大小为 L B，则第 i 个元素的地址为：元素首地址 + i×L。顺序存储不容易插入和删除。
链式存储：每个结点不仅有数据本身，还有体现数据之间关系的指针，结点由值域和指针域组成。单向链表中每个结点有一个指针，指向其后继结点；最后一个结点的指针域为空，头结点的值域为空，指针域为空表示单向链表的结束。链式存储很容易插入与删除。

二、栈与队列
1. 栈：运算受限的线性表，只能在栈顶插入与删除，原则是后进先出（LIFO）。
2. 栈的存储：顺序存储时栈底下标为 0，插入、删除在栈顶进行，指针为 -1 表示栈空；链式存储的操作方式与单向线性链表一致，表头指针指向空表示栈空。
3. 队列：运算受限的线性表，插入在表尾，删除在表头，原则是先进先出（FIFO）。
