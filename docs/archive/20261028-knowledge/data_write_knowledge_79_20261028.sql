1. 树的定义：树是重要的非线性结构。有且仅有一个结点没有前驱，称为根结点；除根结点外，其余各结点有且仅有一个前驱；所有结点都可以有 0 个或多个后继结点。
2. 树的表示：树形表示、二元组、集合、凹入、广义表。
3. 树的基本概念：结点的度是该结点后继结点的数目；树的度是所有结点中度的最大值；度大于 0 的结点为分支结点；度等于 0 的结点为叶子结点（终端结点）；根结点为第一层，向下依次类推，树的深度是所有结点中的最大层数；子树从左到右有序的树为有序树，没有特别说明时认为是有序树；森林是多棵互不相交的树。
4. 树的性质：树的结点数目等于所有结点的度之和加 1；度为 K 的树第 i 层上至多有 K^(i-1) 个结点；深度为 h 的 K 叉树至多有 (K^h - 1)/(K - 1) 个结点；具有 n 个结点的 K 叉树的最小深度可按深度为 h 时的结点数逆推。
5. 二叉树：每个结点至多有两棵子树，且左右子树有次序之分，共有 5 种基本形态。满二叉树每层都是满的，第 i 层上的结点数为 2^(i-1) 个；完全二叉树除最后一层外其余各层都满，最后一层的结点集中在左边；理想二叉树除最后一层外其余各层都满，最后一层结点可任意分布。二叉树不是树的特例，它有自身定义，子树顺序不能颠倒。
6. 二叉树的存储：顺序存储时对完全二叉树从根开始按层次编号，根为 1 并放入 1# 下标；对不完全二叉树同样按层次编号，缺失元素的编号保留。链式存储的结点包括值域、指向左孩子的左指针域和指向右孩子的右指针域，指针域为空表示没有对应孩子。
