互联网应用的发展阶段：1996年前后以数据传输、电子邮件为主；2006年前后以万维网、电子商务、视频点播、在线游戏、社交网络为主；当前进一步扩展到物品追踪、环境感知、自动识别、智能电网、智能交通、智能物流、绿色建筑等领域。

应用层关键技术：
（1）M2M：M2M是Machine-to-Machine（机器对机器）的缩写，根据不同应用场景，往往也被解释为Man-to-Machine（人对机器）、Machine-to-Man（机器对人）、Mobile-to-Machine（移动网络对机器）、Machine-to-Mobile（机器对移动网络）。
（2）云计算：云计算是分布式计算、并行计算和网格计算的发展，或者说是这些计算机科学概念的商业实现。云计算通过共享基础资源（硬件、平台、软件）的方法，将巨大的系统池连接在一起以提供各种IT服务。
（3）人工智能：人工智能是探索研究使各种机器模拟人的某些思维过程和智能行为（如学习、推理、思考、规划等），使人类的智能得以物化与延伸的一门学科。
（4）数据挖掘：数据挖掘是从大量的、不完全的、有噪声的、模糊的及随机的实际应用数据中，挖掘出隐含的、未知的、对决策有潜在价值的数据的过程。
（5）中间件：中间件是指网络环境下处于操作系统、数据库等系统软件和应用软件之间的一种起连接作用的分布式软件，主要解决异构网络环境下分布式应用软件的互联与互操作问题，提供标准接口、协议，屏蔽实现细节，提高应用系统易移植性。
（6）嵌入式系统：嵌入式系统就是嵌入到目标体系中的专用计算机系统，它以应用为中心、以计算机技术为基础，并且软硬件可裁剪，适用于应用系统对功能、可靠性、成本、体积、功耗有严格要求的专用计算机系统。物联网的各种智能终端大部分表现为嵌入式系统，可以说没有嵌入式技术就没有物联网应用的美好未来。
（7）大数据技术：大数据是指在互联网和以大规模分布式计算为代表的平台支持下被采集、存储、分析和应用的、具有产生更高决策价值的巨量、高增长率和多样化的信息资产。大数据系统总是由数据采集、数据存储、数据分析（或数据处理与服务）和数据应用四个部分构成。在物联网中，大数据技术扮演着海量数据存储与分析处理的重要角色，是支撑物联网应用的重要系统平台。
（8）分布式并行计算：并行计算可分为时间上的并行和空间上的并行。时间上的并行就是指流水线技术，而空间上的并行则是指用多个处理器并发地执行计算。物联网与分布式并行计算关系密切，它是支撑物联网的重要计算环境之一。
（9）多媒体与虚拟现实：媒体技术可以使物联网感知世界、表现感知结果的手段更丰富、更形象、更直观；虚拟现实技术成为人类探索客观世界规律的三大手段之一，也是未来物联网应用的一个重要技术手段。

物联网的总体架构：根据信息生成、传输、处理和应用的过程，可以把物联网系统从结构上分为四层：感知层、传输层、支撑层、应用层。

短距离无线通信：短距离无线通信泛指在较小区域（数百米）内提供无线通信的技术，目前常见的技术大致有802.11系列无线局域网、蓝牙、NFC（近场通信）技术和红外传输技术。

Wibree：超低功耗蓝牙无线技术，又被称作“小蓝牙”，是一种能够方便快捷地接入手机和一些诸如翻页控件、个人掌上电脑（PDA）、无线计算机外围设备、娱乐设备和医疗设备等便携式设备的低能耗无线局域网（WLAN）互动接入技术。Wibree技术可以在设备间进行连接，并且突破了蓝牙固有的能量局限，功耗仅为蓝牙的1/10。Wibree技术的信号能够在2.4GHz的无线电频率上以最高达1Mbps的数据传输率覆盖方圆5~10m的范围。Wibree技术可以很方便地和蓝牙技术一起部署到一块独立宿主芯片上或一块双模芯片上。Wibree由于其自身短距离、超低能耗、高数据传输率的特点，被广泛认为是新一代的蓝牙技术，或者是蓝牙技术的补充。

Wi-Fi：Wi-Fi（Wireless Fidelity，无线高保真）的正式名称是IEEE 802.11b，与蓝牙一样同属于短距离无线通信技术。Wi-Fi速率最高可达11Mb/s。虽然在数据安全性方面比蓝牙技术要差一些，但在电波的覆盖范围方面却略胜一筹，可达100m左右。Wi-Fi是以太网的一种无线扩展，理论上只要用户位于一个接入点四周的一定区域内，就能以最高约11Mb/s的速度接入Web；但实际上如果有多个用户同时通过一个接入点接入，带宽被多个用户分享，Wi-Fi的连接速度一般将只有几百kb/s。Wi-Fi信号不受墙壁阻隔，但在建筑物内的有效传输距离小于户外。

WiGig：WiGig（Wireless Gigabit，无线千兆比特）是一种更快的短距离无线技术，可用于在家中快速传输大型文件。WiGig和WirelessHD都使用60GHz的频段，这一基本尚未使用的频段可以在近距离内实现极高的传输速率。WiGig不是WirelessHD（无线高清）等技术的直接竞争对手，它拥有更广泛的用途，其目标不仅是连接电视机，还包括手机、摄像机和个人电脑。WiGig技术并非只是面向视频和文件的传输，该标准的协议适应层目前正在发展当中，希望支持特定的系统接口，以替代HDMI或Display Port，这意味着未来显卡和显示器之间也可以通过无线连接，NVIDIA、AMD和Intel齐聚WiGig就显示了这一前景。

IrDA：是一种利用红外线进行点对点通信的技术，是第一个实现无线个人局域网（Wireless Personal Area Network，WPAN）的技术。目前它的软硬件技术都很成熟，在PDA、手机等小型移动设备上广泛使用。事实上，当今每一个出厂的PDA及许多手机、笔记本电脑、打印机等产品都支持IrDA。IrDA的主要优点是无需申请频率的使用权，因而红外通信成本低廉，并且还具有移动通信所需的体积小、功耗低、连接方便、简单易用的特点；此外红外线发射角度较小，传输上安全性高。IrDA的不足在于它是一种视距传输，两个相互通信的设备之间必须对准，中间不能被其他物体阻隔，因而该技术只能用于2台（非多台）设备之间的连接；而蓝牙就没有此限制，且不受墙壁的阻隔。IrDA目前的研究方向是如何解决视距传输问题及提高数据传输率。

UWB：超宽带（Ultra Wideband，UWB）技术是一种无线载波通信技术，它不采用正弦载波，而是利用纳秒级的非正弦波窄脉冲传输数据，因此其所占的频谱范围很宽。UWB可在非常宽的带宽上传输信号，美国FCC对UWB的规定为在3.1~10.6GHz频段中占用500MHz以上的带宽。UWB技术具有系统复杂度低、发射信号功率谱密度低、对信道衰落不敏感、低截获能力、定位精度高等优点，尤其适用于室内等密集多径场所的高速无线接入，非常适于建立一个高效的无线局域网或无线个域网（WPAN）。UWB主要应用在小范围、高分辨率、能够穿透墙壁、地面和身体的雷达和图像系统中。

