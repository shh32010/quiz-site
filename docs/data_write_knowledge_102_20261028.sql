十一、网络安全

没有绝对安全的网络，只能在安全性与实用性（成本）之间折中。网络信息安全措施必须能覆盖信息的存储、传输、处理等多个方面。

①网络安全四个方面：传输中断（影响信息安全的可用性）、窃听（影响机密性）、篡改（影响完整性）、伪造（影响真实性）。

②安全措施有：真实性鉴别、访问控制、数据加密、数据完整性、数据可用性、防止否认、审计管理。

③数据加密是其他安全措施的基础。

④明文：加密前的原始数据；密文：加密后的数据；加、解密的算法称为密码。

⑤密码中使用的且仅为收发双方知道的信息，称为密钥。

⑥对称密钥加密体系：加密与解密使用同一个密钥。若 n 个用户两两之间通信，则需要 n(n-1)/2 个密钥。算法本身不需要保密，要保密的是密钥。

⑦公开密钥加密体系（非对称）：每一个用户分配一对密钥。发送时用接收方的公开密钥加密，接收时用接收方的私有密钥解密。若 n 个用户两两之间通信，则需要 n 对密钥。目前最常用的公开密钥加密体系是 RSA 系统，与对称加密系统相比安全性高，但计算复杂、速度慢。对称密钥加密系统常用于加密大批量数据，公开密钥加密体系常用于加密关键性核心机密数据。

⑧数字签名：用于保证消息的真实性，是鉴别消息真伪的关键。数字签名无法伪造，且能保证消息的完整性，即消息的任何变化都能被察觉。构成：将消息内容通过摘要算法生成该消息的一个摘要（目的：消息的任何变化都能被察觉，即保证数据的完整性），然后对该摘要用自己的私有密钥加密（保证身份的真实性），得到的就是数字签名。

数字签名中的双重加密：发送方用发送方的私钥加密信息摘要得到数字签名，再用接收方的公钥对已添加了数字签名的消息进行加密；接收方用接收方的私钥对接收的消息解密并取出数字签名，再用发送方的公钥解密数字签名得到信息摘要。

