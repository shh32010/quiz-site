update t_knowledge_point set title = $kp$用例图元素与关系$kp$, content = $kp$用例图元素：

① 参与者（Actor）：用小人图形表示。

② 用例：用椭圆表示。

③ 关系：用连线或箭头表示，包括关联、包含、扩展和泛化。

关联表示参与者与用例之间的交互和通信途径，有时也用带箭头的实线表示，以显式表明发起用例的是参与者。

包含：箭头指向的用例为被包含用例（包含用例），箭头出发的用例为基用例。包含用例是必选的，如果缺少包含用例，基用例就不完整；包含用例必须被执行，不需要满足某种条件，其执行不会改变基用例的行为（«include»）。

扩展：箭头指向的用例为被扩展的用例（基用例），箭头出发的为扩展用例。扩展用例是可选的，缺少扩展用例不会影响基用例的完整性；扩展用例在一定条件下才会执行，并且其执行会改变基用例的行为（«extend»）。

泛化：发出箭头的事物“isa”箭头指向的事物。泛化关系是一般与特殊的关系，发出箭头的一方代表特殊一方，箭头指向的一方代表一般一方；特殊一方继承一般方的特性并增加新的特性。包含和扩展是用例图特有的关系，泛化在其他类图中同样存在。

包含用例：当可以从两个或两个以上的用例中提取公共行为时，应使用包含关系表示。提取出来的公共用例称为抽象用例，原始用例称为基本用例（基础用例）。«include» 是包含关系的构造型，箭头指向抽象用例。例如创建新订单和更新订单都需要检查用户账户是否正确，则“创建新订单”“更新订单”与“检查用户账号”之间是包含关系。包含关系表示一个用例执行的功能中总包括被包含用例的功能；当某用例的事件流过于复杂时，也可以抽象出一个基础用例来包含这些较细的用例，例如“添加密码”“修改密码”“删除密码”可以抽象成基用例“管理密码”。使用包含关系还可以避免同一段事件流在不同用例中描述不一致，需要修改公共需求时只需修改一个用例。

扩展用例：扩展用于处理同一用例的多种不同场景，即根据情况可能发生多种分支时，可将该用例分为一个基本用例和一个或多个扩展用例，使描述更清晰。扩展用例为基用例添加新的行为，可以访问基用例的属性，因此能根据基用例中扩展点的当前状态决定是否执行自己，而扩展用例对基用例不可见。扩展关系是指一个用例的执行可能需要由其他用例的功能来扩展。

