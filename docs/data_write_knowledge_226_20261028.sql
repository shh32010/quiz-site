三、专家系统
专家系统（Expert System，ES）是一种知识信息的加工处理系统，也是人工智能最重要的应用系统。它通常由两部分组成：一是称为知识库的知识集合，包含待处理问题的领域知识；二是称为推理机的程序模块。推理是指从已有事实推出新事实（或结论）的过程。专家系统的结构包含人机界面、知识库、推理机、动态数据库、知识库管理系统和解释模块。

四、人类智能的特性
表现在四个方面：能感知客观世界的信息；能通过思维对获得的知识进行加工处理；能通过学习积累知识、适应环境变化；能对外界的刺激作出反应并传递信息。

五、主要发展方向
1. 运算智能，即快速计算和记忆存储能力。人工智能各项技术的发展并不均衡，现阶段计算机在运算能力和存储能力上更具优势。1996年IBM“深蓝”计算机战胜国际象棋世界冠军卡斯帕罗夫，此后人类在强运算型比赛方面已难以战胜机器。
2. 感知智能，即视觉、听觉、触觉等感知能力，人和动物都具备，能通过各种感知能力与自然界交互。自动驾驶汽车即通过激光雷达等感知设备和人工智能算法实现感知智能。机器在感知世界方面比人类更有优势：人类是被动感知，机器可以主动感知，如激光雷达、微波雷达和红外雷达。借助深度神经网络和大数据的成果，机器在感知智能方面已越来越接近人类。
3. 认知智能，通俗讲是“能理解、会思考”。人类有语言才有概念、才有推理，概念、意识、观念等都是人类认知智能的表现。

