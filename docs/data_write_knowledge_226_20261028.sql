七、人工智能的特征
1. 由人类设计、为人类服务：按照人类设定的程序逻辑或软件算法，通过人工与机器学习工作，为人类提供延伸人类能力的服务。
2. 本质为计算、基础为数据：其本质体现为计算，通过对数据的采集、加工和存储形成有价值的信息流和知识模型。
3. 能感知环境、能产生反应：借助传感器等设备收集信息，像人一样通过听觉、视觉、嗅觉、触觉等接收环境信息，并对外界输入产生文字、语音、表情、动作（控制执行机构）等反应，甚至影响环境或人类。
