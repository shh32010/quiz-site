人工智能（Artificial Intelligence，缩写 AI）的定义可分为“人工”与“智能”两部分，它是研究、开发用于模拟、延伸和扩展人的智能的理论、方法、技术及应用系统的一门新的技术科学。对人工智能研究影响较大的有符号主义（基于逻辑推理的智能模拟方法）、联结主义（受脑科学启发）和行为主义（基于“知识—行动”）三大学派。

