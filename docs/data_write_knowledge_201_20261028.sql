## 国内外主流云服务平台

Amazon 的云计算产品总称为 Amazon Web Service（AWS），主要由 S3（Simple Storage Service，简单存储服务）、EC2（Elastic Compute Cloud，可伸缩计算云）、SQS（Simple Queuing Service，简单消息队列服务）和 SimpleDB 四部分组成，此外还提供内容推送服务 CloudFront、电子商务服务 DevPay 和 FPS 服务。其中 Amazon EC2 提供安全且可调整大小的计算容量，需要时启动应用程序，无需预先承诺。

Google 云计算技术包括 Google 文件系统（GFS）、分布式计算编程模型（MapReduce）、分布式锁服务（Chubby）和分布式结构化数据表（BigTable）。其中 GFS 提供海量数据存储和访问能力，MapReduce 使海量信息的并行处理变得简单易行，Chubby 保证分布式环境下并发操作的同步问题，BigTable 使海量数据的管理和组织十分方便。

微软 Azure 的云端技术绝大多数是自有的，如 Windows 操作系统、SQL Server 数据库、Office 办公软件、活动目录等，优点是架构简洁、综合成本低；缺点是开放性有待提高，目前虽已引入 Linux、Hadoop、Eclipse 等开源产品，但仍远远不够。微软在云中开发方面比较有优势，包括开发移动应用、Web 应用和传统软件，并把 Office 办公套件搬上云端，取名 Office 365。

