## 云计算的三种服务模式

根据美国国家标准与技术研究院（NIST）的定义，云计算的服务模式分为基础设施即服务（IaaS）、平台即服务（PaaS）和软件即服务（SaaS）三个层次，这是目前业界最广泛认同的划分。

- 软件即服务（SaaS）：通过 Internet 提供软件，用户无需购买软件，而是向提供商租用基于 Web 的软件来管理企业经营活动，具有“零安装、零维护”的特点，如 iCloud。
- 平台即服务（PaaS）：将软件研发的平台作为一种服务，以 SaaS 的模式提交给用户，因此也是 SaaS 模式的一种应用。PaaS 可以加快 SaaS 的发展，尤其是加快 SaaS 应用的开发速度，如微软的 Windows Azure。
- 基础设施即服务（IaaS）：将硬件资源（服务器、存储、网络和计算能力）打包成服务，通过互联网提供给用户，按使用量计费，可“量身定做”。这里的服务器并非物理服务器，而是通过软件虚拟出来的，如 Amazon EC2。

## IaaS

位于云计算最底层的是 IaaS，有时也叫硬件即服务（Hardware-as-a-Service）。传统的网站服务需要客户自行估算 CPU、内存、存储、网络等基本计算资源，购买昂贵的服务器并托管到运营商机房，再由 IT 维护人员远程监控服务器的运行情况。使用 IaaS 后，用户直接购买服务器基础服务即可。这台服务器可能只是虚拟的，是庞大服务器集群的一部分，但对用户而言就像自己的服务器一样，可以自由安装和定制任意操作系统（如 Windows 或 Linux）。

使用 IaaS 的好处在于，用户不必理会服务器硬件购买、托管、监控、维护等工作，只需专注于自己的网站。

实例：

- 需要运行成批的程序组但没有合适的软硬件环境时，可使用 Amazon 的 EC2。
- 需要在网络上发布一个短期（几天到几个月）的网站时，可使用 Flexiscale。

## PaaS

第二层是 PaaS，向用户提供分布式操作系统、分布式数据库等基础软件服务。公司所有的开发都可以在这一层进行，节省了时间和资源。由于基础硬件和基础软件很多时候密不可分，PaaS 公司一般同时提供 IaaS 和 PaaS 两个层次的服务。

PaaS 公司在 Internet 上提供各种开发和分发应用的解决方案，如虚拟服务器和操作系统，既节省了硬件费用，也让分散的工作室之间的合作更加容易。

实例：

- 需要把大容量文件上传到网络上、供 35000 个用户使用 2 个月时，可使用 Amazon 的 CloudFront。
- 需要在网络上存储大量文档但没有足够存储空间时，可使用 Amazon 的 S3。

## SaaS

第三层是 SaaS，是人们生活中每天都要接触的一层，大多通过网页浏览器实现：任何一个远程服务器上的应用都可以通过网络运行，这就是 SaaS。用户消费的服务完全从桌面系统或智能手机中获取，如微信、微博、云存储、在线视频；国外用户则通过 Netflix、Google Apps、Dropbox 或苹果 iCloud 等使用这些服务。这些网页服务虽然用于商务、娱乐或两者兼有，但也属于云技术的一部分。

实现模式：在中小企业盛行，无需管理软硬件，服务通过浏览器实现。

