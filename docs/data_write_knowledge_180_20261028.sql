## 5G 技术及优势

5G 又称 IMT-2020，即第五代移动通信标准。5G 可使下载和上传速度指数倍增加，延迟（即设备与无线网络之间通信的时间）大大下降。

3GPP 定义了 5G 的三大场景：eMBB 指 3D/超高清视频等大流量移动宽带业务；mMTC 指大规模物联网业务；URLLC 指无人驾驶、工业自动化等需要低时延、高可靠连接的业务。

与 LTE 不同，5G 使用三种不同的频谱频段。低频段频谱低于 1GHz，是美国运营商在 LTE 中主要使用的频段，但正在快速消耗；其覆盖范围大、穿透力强，缺陷是峰值速率最高仅能达到 100Mbps。中频段频谱提供比低频段更快速的覆盖和更低的延迟，但无法像低频段那样穿透建筑物，峰值速率预计可达 1Gbps。高频段频谱即大部分人所认为的 5G，通常指毫米波（mmWave），峰值速率可达 10Gbps，且具备极低的延迟，主要缺陷是覆盖范围小、穿透力较弱。

与 4G 相比，5G 具有“更高网速、低时延高可靠、低功率海量连接”的特点。在超高速率方面，5G 速率最高可达 4G 的 100 倍，实现 10Gb/秒的峰值速率，能够用手机很流畅地看 4K、8K 高清视频，急速畅玩 360 度全景 VR 游戏。在超低时延方面，5G 的空口时延可低至 1 毫秒，仅相当于 4G 的十分之一，远低于人体的应激反应，可广泛应用于自动控制领域。在超大连接方面，5G 每平方公里可以有 100 万的连接数，与 4G 相比用户容量大大增加，除手机终端外还可广泛应用于物联网。

