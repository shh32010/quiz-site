### 1. SOA 面向服务架构

面向服务的架构（service-oriented architecture，SOA）是 Gartner 于 20 世纪 90 年代中期提出的概念：在分布式的环境中，将各种功能都以服务的形式提供给最终用户或者其他服务。

SOA 可以根据需求通过网络对松散耦合的粗粒度应用组件进行分布式部署、组合和使用，服务层是 SOA 的基础。SOA 是一种思想、一种方法论、一种分布式的服务架构，属于粗粒度、松耦合的服务架构，服务之间通过简单、精确定义的接口进行通讯，不涉及底层编程接口和通讯模型。SOA 可以看作是 B/S 模型、XML/Web Service 技术之后的自然延伸。

SOA 并不是某一种具体的技术实现，而是一种系统架构的设计思想。其提出背景是软件系统所解决的问题越来越复杂，会带来难以维护、难以扩展、容易出错等问题，SOA 思想正是为解决这一问题。

SOA 不是 Web Service，Web Service 只是实现 SOA 的一种具体技术方案。Web Service 是平台独立、低耦合、自包含、基于可编程 Web 的应用程序，可使用开放的 XML 标准来描述、发布、发现、协调和配置这些应用程序，用于开发分布式的互操作的应用程序。

SOA 是一种架构设计模式，SOAP、REST、RPC 则是根据这种设计模式构建出来的规范。SOAP（Simple Object Access Protocol，简单对象访问协议）是基于 XML、在分散或分布式的环境中交换信息的简单协议，用于访问网络服务，可使应用程序在 HTTP 之上进行信息交换。WSDL（Web Services Description Language，网络服务描述语言）是一门基于 XML 的语言，用于描述 Web Services 以及如何对它们进行访问。JSON（JavaScript Object Notation，JavaScript 对象表示法）是存储和交换文本信息的语法，类似 XML，但比 XML 更小、更快、更易解析。RPC（Remote Procedure Call，远程过程调用）通常特指在一个应用中调用另一个应用的接口而实现的远程调用。

